# emit_rootfind_embed.R -- write tests/unit/rootfind_embed.mata from the CSVs
# of tools/make_rootfind_embed.R (derivation @sec-rootfind's own rf_* results).
#
# Run (Git Bash; never Rscript -e):
#   "/c/Program Files/R/R-4.6.0/bin/Rscript.exe" tools/emit_rootfind_embed.R <csvdir> [repo]
# Rerunnable and deterministic: the output depends only on the CSVs. Numbers are
# written with %.17g, which round-trips a double exactly; LF line endings.
# Tests do not call R: the emitted file is committed and read by
# tests/unit/test_rootfind.do.

args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) >= 1)
csvdir <- args[1]
repo <- if (length(args) >= 2) args[2] else "."
rd <- function(f) read.csv(file.path(csvdir, f), stringsAsFactors = FALSE, na.strings = "NA",
                           colClasses = "character")
C  <- rd("cases.csv"); Tb <- rd("tables.csv"); Th <- rd("thresholds.csv"); A <- rd("aborts.csv")
prov <- readLines(file.path(csvdir, "provenance.txt"))

# Spec Module 2's status table.
codes <- c("root" = 1, "no sign change up to the bound" = 2, "no sign change up to the usable end" = 3,
           "gap in the usable region" = 4, "more than one sign change" = 5, "ambiguous endpoint sign" = 6,
           "evaluation cap" = 7, "unresolvable point inside the bracket" = 8)
# The evaluator each case runs under (the tests' fakes; 0 = production).
mods <- c("none" = 0,
          "evaluator declares [0.97;0.985] unresolvable (res=0)" = 1,
          "S replaced by -|S| where x < -0.5" = 2,
          "S replaced by 0 where x < -0.5" = 3,
          "dP_drho negated" = 4,
          "dP_drho without its +phi2(a_{r-1};b_{s-1}) corner" = 5,
          "S set to 0 at x == 0 exactly" = 6,
          "S replaced by -sign(x)*max(|x|*c; 2*tau_S)" = 7,
          "S replaced by 0 where |x| < 1e-6" = 8,
          "S set to 0 at x == 0; (0.4999;0.5) unusable" = 11,
          "dP_drho negated; S set to 0 at x == 0; (-0.5;-0.4999) unusable" = 12,
          "S set to tau_S/2 on [0.996;0.9975]" = 13,
          "endpoint check's cap set to 10 per side" = 0)
C$mod <- ifelse(grepl("^evaluator declares the single point", C$modification), 9, mods[C$modification])
stopifnot(!is.na(C$mod), C$expected_status %in% names(codes))
g <- function(v) ifelse(is.na(v) | v == "NA", ".", sprintf("%.17g", as.numeric(v)))

out <- c(
  "*! rootfind_embed.mata -- GENERATED by tools/emit_rootfind_embed.R; do not edit.",
  "*! Reference values from derivation @sec-rootfind, via tools/make_rootfind_embed.R.",
  paste0("*! ", prov[grepl("^(repo_head|qmd_dirty|qmd_md5|R=)", prov)]),
  "*! Columns of the case matrix: status, converged, rho, rk_rho, rk_budget, B, cap,",
  "*! capc, evaluator (0 production; 1-13 the test's fakes), bracket_lo, bracket_hi,",
  "*! evals, evals_check, tau_S at rho. Status codes: spec Module 2's table (1 = root).",
  "",
  "version 16",
  "",
  "mata:",
  "",
  "void dwlsmv_t_rf_embed(string colvector id, string colvector set, real matrix M,",
  "                       real matrix T, real matrix H)",
  "{",
  "    id  = J(0, 1, \"\")",
  "    set = J(0, 1, \"\")",
  "    M   = J(0, 14, .)",
  "    T   = J(0, 4, .)",
  "    H   = J(0, 4, .)")
for (k in seq_len(nrow(C))) {
  c1 <- C[k, ]
  out <- c(out,
    sprintf("    id  = id \\ \"%s\"", c1$case_id),
    sprintf("    set = set \\ \"%s\"", c1$set),
    sprintf("    M   = M \\ (%s)", paste(c(codes[[c1$expected_status]], g(c1$expected_converged), g(c1$expected_rho),
                                         g(c1$rk_rho), g(c1$rk_budget), g(c1$B), g(c1$cap), g(c1$capc), c1$mod,
                                         g(c1$bracket_lo), g(c1$bracket_hi), g(c1$evals), g(c1$evals_check), g(c1$tau_S)),
                                       collapse = ", ")))
  tk <- Tb[Tb$case_id == c1$case_id, ]
  out <- c(out, sprintf("    T   = T \\ (%d, %s, %s, %s)", k, tk$r, tk$s, tk$n))
  hk <- Th[Th$case_id == c1$case_id, ]
  out <- c(out, sprintf("    H   = H \\ (%d, %d, %s, %s)", k, ifelse(hk$var == "a", 1L, 2L), hk$k, g(hk$value)))
}
out <- c(out, "}", "")
# The aborts use the first FAIL pair's table and thresholds (tables.csv holds them under each abort id).
tk <- Tb[Tb$case_id == A$case_id[1], ]; hk <- Th[Th$case_id == A$case_id[1], ]
out <- c(out,
  "// The first FAIL pair, for the abort cases; x_inf is the section's unresolvable end.",
  "void dwlsmv_t_rf_abortpair(real matrix n, real colvector a, real colvector b, real scalar xinf)",
  "{",
  sprintf("    n = J(%d, %d, 0)", max(as.integer(tk$r)), max(as.integer(tk$s))),
  sprintf("    n[%s, %s] = %s", tk$r, tk$s, tk$n),
  sprintf("    a = (%s)'", paste(g(hk$value[hk$var == "a"]), collapse = ", ")),
  sprintf("    b = (%s)'", paste(g(hk$value[hk$var == "b"]), collapse = ", ")),
  sprintf("    xinf = %s", g(A$bracket_hi[A$case_id == "A_unresolvable_bracket_end"])),
  "}", "", "end")
con <- file(file.path(repo, "tests", "unit", "rootfind_embed.mata"), "wb")
writeLines(out, con, sep = "\n"); close(con)
cat("wrote", length(out), "lines,", nrow(C), "cases\n")
